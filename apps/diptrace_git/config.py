"""Portable selection and explicit native reconstruction instructions."""
from pathlib import PurePosixPath
from .files import read_json

CONFIG = '.diptrace-git.json'
SIGNATURE = 'diptrace-git/2'
LEGACY = 'diptrace-git/1'
METADATA_SUFFIX = '.git.json'
FAMILIES = {'dch': 'schematic', 'dip': 'pcb', 'eli': 'component', 'lib': 'pattern'}
NOTE = 'Generated by diptrace-git: native output version and reconstruction settings.'


class ConfigurationError(ValueError):
    """Invalid local usage or portable project settings."""


def native_format(binary):
    key = PurePosixPath(binary).suffix.lower().lstrip('.')
    if key not in FAMILIES:
        raise ValueError(f'not a native DipTrace filename: {binary}')
    return key


def serialization(binary, text_format):
    return native_format(binary) + 'xml' if text_format in ('xml', 'dchxml') else 'asc'


def validate_pathspec(pattern):
    if not isinstance(pattern, str) or not pattern or any(c in pattern for c in '\r\n\0'):
        raise ConfigurationError('pathspecs must be nonempty single-line strings')
    if pattern.startswith(':(') and 'attr:' in pattern.split(')', 1)[0]:
        raise ConfigurationError('attribute pathspec magic is unavailable for virtual native filenames; use paths or globs')


def load_config(repo):
    path = repo.path(CONFIG)
    if not path.is_file():
        raise ConfigurationError('no .diptrace-git.json; run init first')
    try:
        value = read_json(path)
    except ValueError as error:
        raise ConfigurationError(str(error)) from None
    if value.get('format') == LEGACY:
        raise ConfigurationError('legacy diptrace-git configuration; run init --migrate before using this version')
    if value.get('format') != SIGNATURE or value.get('text_format') not in ('xml', 'asc'):
        raise ConfigurationError('unsupported diptrace-git configuration')
    if type(value.get('fallback_earlier', False)) is not bool or not isinstance(value.get('rules'), list):
        raise ConfigurationError('invalid diptrace-git settings')
    for rule in value['rules']:
        if (not isinstance(rule, dict) or type(rule.get('enabled')) is not bool
                or not isinstance(rule.get('pathspecs'), list) or not rule['pathspecs']):
            raise ConfigurationError('selection entries need enabled and nonempty pathspecs')
        for pattern in rule['pathspecs']:
            validate_pathspec(pattern)
    return value


def new_config(text_format='xml', fallback=False):
    return {'format': SIGNATURE, 'text_format': 'xml' if text_format == 'dchxml' else text_format,
            'fallback_earlier': fallback, 'rules': []}


def companions(binary, text_format):
    extension = 'xml' if text_format.endswith('xml') else 'asc'
    return binary + '.git.' + extension, binary + METADATA_SUFFIX


def companion_format(metadata):
    return serialization(metadata['binary']['path'], PurePosixPath(metadata['text']['path']).suffix.lstrip('.'))


def manifest(binary, version, text_format):
    text, _ = companions(binary, text_format)
    return {'format': SIGNATURE, 'purpose': NOTE,
            'binary': {'path': binary, 'version': version}, 'text': {'path': text}}


def load_manifest(repo, name):
    value = read_json(repo.path(name))
    try:
        binary = value['binary']['path']
        version = value['binary']['version']
        text = value['text']['path']
        native_format(binary)
        if (value['format'] != SIGNATURE or type(version) is not int
                or PurePosixPath(text).suffix not in ('.asc', '.xml')
                or companions(binary, companion_format(value)) != (text, name)):
            raise ValueError()
        repo.path(binary)
        repo.path(text)
    except (KeyError, TypeError, AttributeError, ValueError):
        raise ValueError(f'{name}: invalid or legacy reconstruction metadata') from None
    return value
